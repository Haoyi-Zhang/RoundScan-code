#!/usr/bin/env python3
"""Rebuild every derived result table from the authoritative raw task records.

The raw JSON records and stored certificate files are the only measurement
sources.  This script rewrites metrics CSVs, JSON summaries, the
stress-by-horizon table, and the LaTeX row fragment used by the manuscript.  It
also checks that each recorded certificate byte count equals the actual stored
file size, preventing silently mixed campaign snapshots.
"""
from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from run_campaign import METHODS, collect_split

EXPECTED = {
    "frozen": {"rows": 360, "instances": 72},
    "stress": {"rows": 80, "instances": 16},
}
COVER_METHODS = ("interval", "fresh", "syntactic", "residue")
DISPLAY = {
    "interval": "Independent intervals",
    "fresh": "Fresh residuals",
    "syntactic": "Syntactic sharing",
    "residue": "Modular sharing",
    "exact-dp": "Exact finite-state DP",
}


def _read_raw(split: str) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for path in sorted((ROOT / "results" / "raw" / split).glob("*.json")):
        with path.open("r", encoding="utf-8") as handle:
            value = json.load(handle)
        value["_path"] = str(path.relative_to(ROOT))
        rows.append(value)
    return rows


def _certificate_consistency(split: str, raw: list[dict[str, Any]]) -> dict[str, Any]:
    checked = 0
    errors: list[str] = []
    for entry in raw:
        task = entry.get("task", {})
        if task.get("kind") != "cover" or task.get("status") == "unknown":
            continue
        method = entry["method"]
        rel = task.get("certificate")
        path = ROOT / rel if rel else ROOT / "results" / "certificates" / split / f"{entry['case']}-{method}.json"
        if not path.exists():
            errors.append(f"{entry['_path']}: missing certificate {path.relative_to(ROOT)}")
            continue
        actual = path.stat().st_size
        recorded = task.get("certificate_bytes")
        if actual != recorded:
            errors.append(f"{entry['_path']}: certificate bytes raw={recorded} actual={actual}")
        checker = entry.get("checker")
        if not isinstance(checker, dict) or not checker.get("accepted"):
            errors.append(f"{entry['_path']}: conclusive cover lacks an accepted checker record")
        checked += 1
    return {"checked_certificates": checked, "errors": errors, "ok": not errors}


def _method_summary(rows: list[dict[str, Any]], method: str) -> dict[str, Any]:
    selected = [row for row in rows if row["method"] == method]
    return {
        "status_counts": dict(Counter(row["status"] for row in selected)),
        "nodes": sum(int(row["nodes"] or 0) for row in selected),
        "certificate_bytes": sum(int(row["certificate_bytes"] or 0) for row in selected),
        "producer_cpu_seconds": sum(float(row["production_cpu_seconds"] or 0.0) for row in selected),
        "checker_cpu_seconds": sum(float(row["checker_cpu_seconds"] or 0.0) for row in selected),
    }


def _write_stress_by_horizon(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    output: list[dict[str, Any]] = []
    horizons = sorted({int(row["horizon"]) for row in rows})
    for horizon in horizons:
        for method in METHODS:
            selected = [row for row in rows if int(row["horizon"]) == horizon and row["method"] == method]
            counts = Counter(row["status"] for row in selected)
            output.append({
                "horizon": horizon,
                "method": method,
                "safe": counts.get("safe", 0),
                "violated": counts.get("violated", 0),
                "unknown": counts.get("unknown", 0),
                "nodes": sum(int(row["nodes"] or 0) for row in selected),
            })
    path = ROOT / "results" / "stress-by-horizon.csv"
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=("horizon", "method", "safe", "violated", "unknown", "nodes"))
        writer.writeheader()
        writer.writerows(output)
    return output


def _latex_integer(value: int) -> str:
    return f"{value:,}"


def _latex_label(value: int) -> str:
    # Safe inside an explicit-symbolic PGFPlots point-meta field.
    return f"{value:,}".replace(",", "{,}")


def _write_paper_fragment(frozen: dict[str, Any], stress_horizon: list[dict[str, Any]]) -> str:
    lines = [
        "% Generated by artifact/scripts/analyze_results.py from results/raw/*.json.",
        "% Do not edit numeric entries by hand.",
    ]
    macro_names = {
        "interval": "Interval",
        "fresh": "Fresh",
        "syntactic": "Syntactic",
        "residue": "Residue",
    }
    for method in COVER_METHODS:
        summary = frozen[method]
        stem = macro_names[method]
        lines.extend([
            f"\\newcommand{{\\Frozen{stem}NodesRaw}}{{{summary['nodes']}}}",
            f"\\newcommand{{\\Frozen{stem}NodesLabel}}{{{_latex_label(summary['nodes'])}}}",
        ])

    frozen_rows: list[str] = []
    for method in COVER_METHODS:
        summary = frozen[method]
        frozen_rows.append(
            f"{DISPLAY[method]} & {_latex_integer(summary['nodes'])} & "
            f"{_latex_integer(summary['certificate_bytes'])} & "
            f"{summary['producer_cpu_seconds']:.3f} & {summary['checker_cpu_seconds']:.3f}\\\\"
        )
    exact = frozen["exact-dp"]
    frozen_rows.append(
        f"{DISPLAY['exact-dp']} & -- & -- & {exact['producer_cpu_seconds']:.3f} & --\\\\"
    )
    lines.append("\\newcommand{\\FrozenResultsRows}{%")
    lines.extend(f"  {row}" for row in frozen_rows)
    lines.append("}")

    by_horizon = {(int(row["horizon"]), row["method"]): row for row in stress_horizon}
    horizons = sorted({int(row["horizon"]) for row in stress_horizon})
    lines.append("\\newcommand{\\StressResultsRows}{%")
    totals = {method: 0 for method in METHODS}
    for horizon in horizons:
        values = []
        for method in METHODS:
            safe = int(by_horizon[(horizon, method)]["safe"])
            totals[method] += safe
            values.append(str(safe))
        lines.append(f"  {horizon} & " + " & ".join(values) + "\\\\")
    lines.append("  \\midrule")
    lines.append("  Total & " + " & ".join(str(totals[method]) for method in METHODS) + "\\\\")
    lines.append("}")

    text = "\n".join(lines) + "\n"
    (ROOT / "results" / "paper-results.tex").write_text(text, encoding="utf-8")
    return text


def main() -> int:
    report: dict[str, Any] = {"status": "PASS", "splits": {}, "certificate_files": {}}
    collected: dict[str, list[dict[str, Any]]] = {}
    for split, expected in EXPECTED.items():
        rows = collect_split(split)
        collected[split] = rows
        instances = len({row["case"] for row in rows})
        grid = Counter((row["case"], row["method"]) for row in rows)
        grid_ok = all(count == 1 for count in grid.values()) and len(grid) == expected["rows"]
        ok = len(rows) == expected["rows"] and instances == expected["instances"] and grid_ok
        report["splits"][split] = {
            "rows": len(rows),
            "instances": instances,
            "expected_rows": expected["rows"],
            "expected_instances": expected["instances"],
            "complete_case_method_grid": grid_ok,
            "ok": ok,
        }
        if not ok:
            report["status"] = "FAIL"
        cert_report = _certificate_consistency(split, _read_raw(split))
        report["certificate_files"][split] = cert_report
        if not cert_report["ok"]:
            report["status"] = "FAIL"

    frozen = {method: _method_summary(collected["frozen"], method) for method in METHODS}
    stress_horizon = _write_stress_by_horizon(collected["stress"])
    fragment = _write_paper_fragment(frozen, stress_horizon)
    paper_copy = ROOT.parent / "paper" / "generated-results.tex"
    paper_sync: dict[str, Any]
    if paper_copy.exists():
        current = paper_copy.read_text(encoding="utf-8")
        paper_sync = {"checked": True, "matched": current == fragment, "path": str(paper_copy)}
        if current != fragment:
            report["status"] = "FAIL"
    else:
        paper_sync = {"checked": False, "matched": None, "path": None}
    report["paper_fragment_sync"] = paper_sync
    report["frozen_table_source"] = frozen
    report["stress_by_horizon_rows"] = len(stress_horizon)

    out = ROOT / "results" / "analysis-audit.json"
    out.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0 if report["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
